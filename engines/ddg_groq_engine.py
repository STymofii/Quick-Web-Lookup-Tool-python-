from groq import Groq
from ddgs import DDGS
from engines.engine import Engine


class DDG_Groq_Engine(Engine):
    """DDGS search + Groq summarizer.

    Hybrid engine: real search results are fetched via DDGS and then passed
    as context to the Groq LLM, which extracts the shortest factual answer.

    Requires GROQ_API_KEY. Not a pure search engine — the final answer is
    generated by an LLM and may hallucinate if the context is insufficient.

    On any error returns an empty string (so it is not counted as a valid
    answer by the benchmark).
    """

    def __init__(self, api_key):
        self.api_key = api_key

    def get_web_search_results(self, query: str) -> str:
        """Fetch top-3 DDGS results and format them as plain text context."""
        try:
            with DDGS() as ddgs:
                results = list(ddgs.text(query, max_results=3))
                if not results:
                    return ""
                return "\n".join(
                    f"{r.get('title', '')}: {r.get('body', '')}"
                    for r in results
                )
        except Exception as e:
            print(f"[DDG+Groq] search error: {e}")
            return ""

    def search(self, query: str, language_code: str = "ru") -> str:
        if not self.api_key:
            return ""

        web_context = self.get_web_search_results(query)
        if not web_context:
            web_context = "No data found online. Answer based on your knowledge."

        try:
            client = Groq(api_key=self.api_key)
            system_prompt = (
                f"You are a data verifier. Your only task is to read the "
                f"provided context from the internet and extract from it the "
                f"shortest, most precise answer to the user's question. "
                f"Answer strictly in language '{language_code}'. "
                f"No greetings, no politeness, no unnecessary words. "
                f"Just the bare facts (number, name, date). If there are "
                f"contradictions in the context, choose the most recent or "
                f"authoritative fact. Try to extract data from context as "
                f"accurately as possible if available."
            )

            completion = client.chat.completions.create(
                model="llama-3.1-8b-instant",
                messages=[
                    {"role": "system", "content": system_prompt},
                    {
                        "role": "user",
                        "content": f"Context:\n{web_context}\n\nQuery: {query}",
                    },
                ],
                temperature=0.0,
            )
            return completion.choices[0].message.content.strip()

        except Exception as e:
            print(f"[DDG+Groq] {e}")
            return ""


# ---- module-level interface required by the task ----
_instance = None

def search(query: str, language_code: str = "ru") -> str:
    """Module-level wrapper. Returns '' if API key is missing."""
    global _instance
    import os
    if not os.getenv("GROQ_API_KEY"):
        return ""
    if _instance is None:
        _instance = DDG_Groq_Engine(os.getenv("GROQ_API_KEY"))
    return _instance.search(query, language_code)
